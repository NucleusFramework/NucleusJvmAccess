package dev.nucleusframework.nja.plugin.codegen

import dev.nucleusframework.nja.plugin.ir.ApiFunction
import dev.nucleusframework.nja.plugin.ir.ApiParam
import dev.nucleusframework.nja.plugin.ir.ApiSealedValue
import dev.nucleusframework.nja.plugin.ir.ApiType

/**
 * The JVM side of a façade: a module dispatching each member of the [ApiModel] to the façade, compiled with it (so the
 * Kotlin compiler resolves overloads, defaults, extensions and suspend calls), registered as a service.
 */
class ServerGenerator(private val model: ApiModel, private val libName: String) {
    private val codec = Codec(model, Side.SERVER)

    val packageName = "dev.nucleusframework.nja.generated.${identifier(libName).lowercase()}"
    val className = "Nja${identifier(libName).replaceFirstChar { it.uppercaseChar() }}Module"

    fun generate(): Map<String, String> = mapOf(
        "kotlin/${packageName.replace('.', '/')}/$className.kt" to source(),
        "resources/META-INF/services/dev.nucleusframework.nja.server.NjaModule" to "$packageName.$className\n",
    )

    private fun source(): String = buildString {
        appendLine("// Generated by NJA from the $libName façade. Do not modify.")
        appendLine("@file:Suppress(\"UNUSED_PARAMETER\", \"UNUSED_VARIABLE\", \"UNUSED_ANONYMOUS_PARAMETER\", \"RemoveRedundantQualifierName\", \"unused\")")
        appendLine()
        appendLine("package $packageName")
        appendLine()
        appendLine("import dev.nucleusframework.nja.server.*")
        model.module.packages.forEach { appendLine("import $it.*") }
        appendLine()
        appendLine("class $className : NjaModule(\"$libName\") {")
        appendLine("    override fun call(member: Int, input: WireReader, output: WireWriter, context: CallContext) {")
        appendLine("        when (member) {")
        model.members.forEach { appendLine("            ${it.id} -> m${it.id}(input, output, context)") }
        appendLine("            else -> throw IllegalStateException(\"NJA: unknown member \$member of $libName\")")
        appendLine("        }")
        appendLine("    }")
        model.members.forEach { appendLine(); appendMember(it) }
        appendLine("}")
        appendLine()
        appendCodecs()
    }

    private fun StringBuilder.appendMember(member: Member) {
        appendLine("    private fun m${member.id}(njaR: WireReader, njaW: WireWriter, njaCtx: CallContext) {")
        when (member) {
            is Member.Constructor -> {
                appendArgs(member.params)
                val args = member.params.indices.joinToString(", ") { "p$it" }
                appendLine("        njaW.writeLong(Handles.export(${member.cls.fqName}($args)))")
            }
            is Member.Function -> appendFunction(member.owner, member.fn)
            is Member.Getter -> {
                val target = receiver(member.owner)
                appendLine("        val res = $target.${esc(member.property.name)}")
                appendLine("        ${codec.encode(member.property.type, "res", "njaW")}")
            }
            is Member.Setter -> {
                val target = receiver(member.owner)
                appendLine("        val value = ${codec.decode(member.property.type, "njaR")}")
                appendLine("        $target.${esc(member.property.name)} = value")
            }
            is Member.Invoke -> {
                appendLine("        val fn = Handles.get<${member.type.serverName}>(njaR.readLong())")
                appendArgs(member.type.paramTypes.mapIndexed { i, t -> ApiParam("a$i", t) })
                val args = member.type.paramTypes.indices.joinToString(", ") { "p$it" }
                appendResult(member.type.returnType, "fn($args)")
            }
        }
        appendLine("    }")
    }

    /** The receiver expression, reading the instance's handle first when there is one. */
    private fun StringBuilder.receiver(owner: Owner): String = when (owner) {
        is Owner.Instance -> {
            appendLine("        val self = Handles.get<${owner.fqName}>(njaR.readLong())")
            "self"
        }
        is Owner.Companion -> owner.classFq
        Owner.TopLevel -> error("no receiver")
    }

    private fun StringBuilder.appendFunction(owner: Owner, fn: ApiFunction) {
        val async = fn.isSuspend || fn.returnType is ApiType.FLOW
        if (async) appendLine("        val callId = njaR.readLong()")
        if (fn.returnType is ApiType.FLOW) appendLine("        val credits = njaR.readInt()")
        val call = when (owner) {
            is Owner.Instance, is Owner.Companion -> "${receiver(owner)}.${esc(fn.name)}"
            Owner.TopLevel -> if (fn.isExtension) {
                appendLine("        val self = ${codec.decode(fn.receiverType!!, "njaR")}")
                "self.${esc(fn.name)}"
            } else {
                esc(fn.name)
            }
        }
        appendArgs(fn.params)
        val invocation = "$call(${fn.params.indices.joinToString(", ") { "p$it" }})"
        val returnType = fn.returnType
        when {
            returnType is ApiType.FLOW -> {
                val element = returnType.elementType
                appendLine("        NjaAsync.launchFlow(callId, credits, $invocation) { w, e -> ${codec.encode(element, "e", "w")} }")
            }
            fn.isSuspend -> {
                val encode = if (returnType == ApiType.UNIT) "Unit" else codec.encode(returnType, "v", "w")
                appendLine("        NjaAsync.launchSuspend(callId, njaW, { $invocation }) { w, v -> $encode }")
            }
            else -> appendResult(returnType, invocation)
        }
    }

    private fun StringBuilder.appendArgs(params: List<ApiParam>) {
        params.forEachIndexed { i, p -> appendLine("        val p$i = ${codec.decode(p.type, "njaR")}") }
    }

    private fun StringBuilder.appendResult(type: ApiType, invocation: String) {
        if (type == ApiType.UNIT) {
            appendLine("        $invocation")
        } else {
            appendLine("        val res = $invocation")
            appendLine("        ${codec.encode(type, "res", "njaW")}")
        }
    }

    private fun StringBuilder.appendCodecs() {
        // Objects: their handle and their most specific exported type (the proxy class the app wraps them in)
        appendLine("internal fun nja_writeObject(w: WireWriter, value: Any?) {")
        appendLine("    if (value == null) {")
        appendLine("        w.writeLong(0L)")
        appendLine("        return")
        appendLine("    }")
        appendLine("    w.writeLong(Handles.export(value))")
        appendLine("    w.writeInt(nja_typeOf(value))")
        appendLine("}")
        appendLine()
        appendLine("internal fun nja_typeOf(value: Any): Int = when (value) {")
        model.typeIds.forEach { (fq, id) -> appendLine("    is $fq -> $id") }
        appendLine("    else -> -1")
        appendLine("}")
        for (dc in model.module.dataClasses) {
            appendLine()
            appendLine("internal fun nja_write_${dc.simpleName}(w: WireWriter, value: ${dc.fqName}) {")
            dc.fields.forEach { f -> appendLine("    ${codec.encode(f.type, "value.${esc(f.name)}", "w")}") }
            appendLine("}")
            appendLine()
            appendLine("internal fun nja_read_${dc.simpleName}(r: WireReader): ${dc.fqName} = ${dc.fqName}(")
            dc.fields.forEach { f -> appendLine("    ${esc(f.name)} = ${codec.decode(f.type, "r")},") }
            appendLine(")")
        }
        for (v in model.module.sealedValues) appendSealedCodec(v)
    }

    // A sealed value: its case's index, then the case's fields
    private fun StringBuilder.appendSealedCodec(v: ApiSealedValue) {
        appendLine()
        appendLine("internal fun nja_write_${v.simpleName}(w: WireWriter, value: ${v.fqName}) {")
        appendLine("    when (value) {")
        v.cases.forEachIndexed { i, case ->
            appendLine("        is ${case.fqName} -> {")
            appendLine("            w.writeInt($i)")
            case.fields.forEach { f -> appendLine("            ${codec.encode(f.type, "value.${esc(f.name)}", "w")}") }
            appendLine("        }")
        }
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("internal fun nja_read_${v.simpleName}(r: WireReader): ${v.fqName} = when (val njaCase = r.readInt()) {")
        v.cases.forEachIndexed { i, case ->
            if (case.isObject) {
                appendLine("    $i -> ${case.fqName}")
            } else {
                appendLine("    $i -> ${case.fqName}(")
                case.fields.forEach { f -> appendLine("        ${esc(f.name)} = ${codec.decode(f.type, "r")},") }
                appendLine("    )")
            }
        }
        appendLine("    else -> throw IllegalStateException(\"NJA: unknown case \$njaCase of ${v.fqName}\")")
        appendLine("}")
    }

    companion object {
        fun identifier(name: String): String = name.replace(Regex("[^A-Za-z0-9]"), "_")
    }
}
