package dev.nucleusframework.nja.plugin.codegen

import dev.nucleusframework.nja.plugin.ir.ApiClass
import dev.nucleusframework.nja.plugin.ir.ApiFunction
import dev.nucleusframework.nja.plugin.ir.ApiInterface
import dev.nucleusframework.nja.plugin.ir.ApiProperty
import dev.nucleusframework.nja.plugin.ir.ApiSealedCase
import dev.nucleusframework.nja.plugin.ir.ApiSealedValue
import dev.nucleusframework.nja.plugin.ir.ApiSourceDecl
import dev.nucleusframework.nja.plugin.ir.ApiType

/**
 * The app's side of a façade (common Kotlin, for every target): a proxy per class and interface, the value types as
 * the façade declares them, and the extension and top-level functions. All of it lives in [packageName], the
 * façade's API as if it were a local library.
 */
class ClientGenerator(private val model: ApiModel, private val libName: String, private val packageName: String) {
    private val codec = Codec(model, Side.CLIENT)
    private val moduleObject = "Nja_${ServerGenerator.identifier(libName)}"
    private val module = "$moduleObject.index"
    private val membersByOwner = HashMap<Pair<String, String>, Member>()

    init {
        for (m in model.members) {
            when (m) {
                is Member.Function -> ownerKey(m.owner)?.let { membersByOwner[it to signature(m.fn)] = m }
                is Member.Getter -> ownerKey(m.owner)?.let { membersByOwner[it to "get:${m.property.name}"] = m }
                is Member.Setter -> ownerKey(m.owner)?.let { membersByOwner[it to "set:${m.property.name}"] = m }
                else -> Unit
            }
        }
    }

    private fun ownerKey(owner: Owner): String? = when (owner) {
        is Owner.Instance -> owner.fqName
        is Owner.Companion -> "companion:${owner.classFq}"
        Owner.TopLevel -> "top"
    }

    private fun signature(fn: ApiFunction): String =
        "fun:${fn.receiverType?.serverName ?: ""}.${fn.name}(${fn.params.joinToString(",") { it.type.serverName }})"

    fun generate(): Map<String, String> {
        val files = LinkedHashMap<String, String>()
        val dir = packageName.replace('.', '/')
        model.module.classes.forEach { files["$dir/${it.simpleName}.kt"] = file { appendClass(it) } }
        model.module.interfaces.forEach { files["$dir/${it.simpleName}.kt"] = file { appendInterface(it) } }
        model.module.dataClasses.forEach { dc -> dc.source?.let { files["$dir/${dc.simpleName}.kt"] = valueType(it) } }
        model.module.enums.forEach { e -> e.source?.let { files["$dir/${e.simpleName}.kt"] = valueType(it) } }
        model.module.sealedValues.forEach { v -> v.source?.let { files["$dir/${v.simpleName}.kt"] = valueType(it) } }
        files["$dir/$moduleObject.kt"] = file { appendModule() }
        return files
    }

    private fun file(body: StringBuilder.() -> Unit): String = buildString {
        appendLine("// Generated by NJA from the $libName façade. Do not modify.")
        appendLine("@file:OptIn(dev.nucleusframework.nja.NjaInternal::class)")
        appendLine("@file:Suppress(\"UNUSED_ANONYMOUS_PARAMETER\", \"UNUSED_VARIABLE\", \"RedundantVisibilityModifier\", \"unused\")")
        appendLine()
        appendLine("package $packageName")
        appendLine()
        appendLine("import dev.nucleusframework.nja.*")
        appendLine()
        body()
    }

    /** A value type (data class, enum, sealed value hierarchy) exactly as the façade declares it. */
    private fun valueType(source: ApiSourceDecl): String = buildString {
        appendLine("// Generated by NJA from the $libName façade. Do not modify.")
        appendLine("package $packageName")
        appendLine()
        val local = model.module.packages + packageName
        // Only what the declaration uses, and only Kotlin's: the file's other imports are the façade's JVM libraries
        source.imports.filter { directive ->
            val fq = directive.removePrefix("import").substringBefore(" as ").trim()
            val name = directive.substringAfter(" as ", "").trim().ifEmpty { fq.substringAfterLast('.') }
            val pkg = if (fq.endsWith(".*")) fq.removeSuffix(".*") else fq.substringBeforeLast('.', "")
            pkg !in local && (fq.startsWith("kotlin.") || fq.startsWith("kotlinx.")) &&
                (fq.endsWith(".*") || Regex("\\b${Regex.escape(name)}\\b").containsMatchIn(source.text))
        }.forEach { appendLine(it) }
        appendLine()
        appendLine(source.text)
    }

    // ── Classes ─────────────────────────────────────────────────────────────────────────────────────────────────

    private fun StringBuilder.appendClass(cls: ApiClass) {
        val n = cls.simpleName
        val superClass = cls.superClass?.let { model.classesByFq[it] }
        val modifier = when {
            cls.isSealed -> "sealed "
            cls.isAbstract -> "abstract "
            cls.isOpen -> "open "
            else -> ""
        }
        val supers = buildList {
            add(if (superClass != null) "${superClass.simpleName}(njaRef)" else "JvmObject(njaRef)")
            cls.interfaces.forEach { add(model.clientName(it)) }
        }
        appendLine("/** Proxy of the façade's [${cls.fqName}], an object of the JVM. */")
        val visibility = if (cls.isSealed) "protected " else ""
        appendLine("${modifier}class $n @NjaInternal ${visibility}constructor(njaRef: JvmRef) : ${supers.joinToString(", ")} {")
        appendLine("    companion object {")
        if (!cls.isAbstract && !cls.isSealed) {
            model.members.filterIsInstance<Member.Constructor>().filter { it.cls.fqName == cls.fqName }.forEach { ctor ->
                val params = ctor.params.joinToString(", ") { "${esc(it.name)}: ${model.clientType(it.type)}" }
                val writes = ctor.params.joinToString("; ") { codec.encode(it.type, esc(it.name), "njaW") }.ifEmpty { "Unit" }
                appendLine("        operator fun invoke($params): $n =")
                appendLine("            $n(JvmRef(NjaRuntime.call($module, ${ctor.id}, { njaW, njaS -> $writes }) { njaR, _ -> njaR.readLong() }))")
            }
        }
        val companion = "companion:${cls.fqName}"
        cls.companionMethods.forEach { appendFunction(it, membersByOwner.getValue(companion to signature(it)), "        ", receiver = null, modifiers = "") }
        cls.companionProperties.forEach { appendProperty(it, companion, "        ", receiver = null, modifiers = "") }
        appendLine("    }")

        val openMembers = cls.isOpen || cls.isAbstract || cls.isSealed
        cls.methods.forEach { fn ->
            val override = fn.isOverride && inherits(cls, fn.name, isProperty = false)
            val mods = when {
                override -> "override "
                openMembers -> "open "
                else -> ""
            }
            appendFunction(fn, membersByOwner.getValue(cls.fqName to signature(fn)), "    ", receiver = "njaRef", modifiers = mods)
        }
        cls.properties.forEach { p ->
            val override = p.isOverride && inherits(cls, p.name, isProperty = true)
            val mods = when {
                override -> "override "
                openMembers -> "open "
                else -> ""
            }
            appendProperty(p, cls.fqName, "    ", receiver = "njaRef", modifiers = mods)
        }
        // Interface members the class (or its superclasses) doesn't declare: through the interface's own members
        appendMissingInterfaceMembers(cls)
        appendLine("}")

        if (cls.isAbstract || cls.isSealed) {
            appendLine()
            appendLine("/** A JVM object whose most specific exported type is the abstract [$n]. */")
            appendLine("internal class Nja_${n}_Proxy(njaRef: JvmRef) : $n(njaRef)")
        }
    }

    /** Whether a member [name] of [cls] overrides one the app's proxy inherits (an exported supertype, or Any's). */
    private fun inherits(cls: ApiClass, name: String, isProperty: Boolean): Boolean {
        if (!isProperty && name in setOf("toString", "hashCode", "equals")) return true
        val supers = model.superClasses(cls)
        if (supers.any { s -> if (isProperty) s.properties.any { it.name == name } else s.methods.any { it.name == name } }) return true
        return model.allInterfaces(cls.fqName).mapNotNull { model.interfacesByFq[it] }.any { i ->
            if (isProperty) i.properties.any { it.name == name } else i.methods.any { it.name == name }
        }
    }

    private fun StringBuilder.appendMissingInterfaceMembers(cls: ApiClass) {
        val chain = listOf(cls) + model.superClasses(cls)
        val declaredMethods = chain.flatMap { c -> c.methods.map { it.name to it.params.size } }.toSet()
        val declaredProperties = chain.flatMap { c -> c.properties.map { it.name } }.toSet()
        // Members the superclass proxy already gets from its own interfaces don't need repeating
        val inherited = model.superClasses(cls).firstOrNull()?.let { model.allInterfaces(it.fqName) }.orEmpty()
        for (ifaceFq in model.allInterfaces(cls.fqName) - inherited) {
            val iface = model.interfacesByFq[ifaceFq] ?: continue
            iface.methods.filter { (it.name to it.params.size) !in declaredMethods }.forEach { fn ->
                appendFunction(fn, membersByOwner.getValue(iface.fqName to signature(fn)), "    ", receiver = "njaRef", modifiers = "override ")
            }
            iface.properties.filter { it.name !in declaredProperties }.forEach { p ->
                appendProperty(p, iface.fqName, "    ", receiver = "njaRef", modifiers = "override ")
            }
        }
    }

    // ── Interfaces ──────────────────────────────────────────────────────────────────────────────────────────────

    private fun StringBuilder.appendInterface(iface: ApiInterface) {
        val supers = (iface.superInterfaces.map { model.clientName(it) } + "JvmProxy").joinToString(", ")
        appendLine("/** The façade's interface [${iface.fqName}], implemented by proxies of JVM objects. */")
        appendLine("interface ${iface.simpleName} : $supers {")
        iface.methods.forEach { fn ->
            val suspend = if (fn.isSuspend) "suspend " else ""
            val params = fn.params.joinToString(", ") { "${esc(it.name)}: ${model.clientType(it.type)}" }
            appendLine("    ${suspend}fun ${esc(fn.name)}($params): ${model.clientType(fn.returnType)}")
        }
        iface.properties.forEach { p ->
            appendLine("    ${if (p.mutable) "var" else "val"} ${esc(p.name)}: ${model.clientType(p.type)}")
        }
        appendLine("}")
        appendLine()
        appendLine("/** A JVM object whose most specific exported type is the interface [${iface.simpleName}]. */")
        appendLine("internal class Nja_${iface.simpleName}_Proxy(njaRef: JvmRef) : JvmObject(njaRef), ${iface.simpleName} {")
        val all = listOf(iface) + model.allInterfaces(iface.fqName).mapNotNull { model.interfacesByFq[it] }
        for (i in all) {
            i.methods.forEach { fn -> appendFunction(fn, membersByOwner.getValue(i.fqName to signature(fn)), "    ", receiver = "njaRef", modifiers = "override ") }
            i.properties.forEach { p -> appendProperty(p, i.fqName, "    ", receiver = "njaRef", modifiers = "override ") }
        }
        appendLine("}")
    }

    // ── Members ─────────────────────────────────────────────────────────────────────────────────────────────────

    /**
     * A function proxy. [receiver] is the reference whose handle comes first (leased for the call), null for
     * companion and top-level functions.
     */
    private fun StringBuilder.appendFunction(fn: ApiFunction, member: Member, indent: String, receiver: String?, modifiers: String) {
        val params = fn.params.joinToString(", ") { "${esc(it.name)}: ${model.clientType(it.type)}" }
        val returnType = fn.returnType
        // close() (an AutoCloseable's): the JVM object's own, then the proxy's, which releases it; once
        if (receiver != null && fn.name == "close" && fn.params.isEmpty() && returnType == ApiType.UNIT && !fn.isSuspend && !fn.isExtension) {
            appendLine("${indent}override fun close() {")
            appendLine("$indent    if (njaRef.isClosed) return")
            appendLine("$indent    try {")
            appendLine("$indent        $receiver.use { njaH -> NjaRuntime.call($module, ${member.id}, { njaW, njaS -> njaW.writeLong(njaH) }) { _, _ -> } }")
            appendLine("$indent    } finally {")
            appendLine("$indent        super.close()")
            appendLine("$indent    }")
            appendLine("$indent}")
            return
        }
        val extension = if (fn.isExtension) "${model.clientType(fn.receiverType!!)}." else ""
        val head = "$indent$modifiers${if (fn.isSuspend) "suspend " else ""}fun $extension${esc(fn.name)}($params): ${model.clientType(returnType)}"
        val leading = buildList {
            if (receiver != null) add(if (returnType is ApiType.FLOW) "njaW.writeLong(njaS.lease($receiver))" else "njaW.writeLong(njaH)")
            if (fn.isExtension) add(codec.encode(fn.receiverType!!, "this", "njaW"))
        }
        val writes = (leading + fn.params.map { codec.encode(it.type, esc(it.name), "njaW") }).joinToString("; ").ifEmpty { "Unit" }
        val body = when {
            returnType is ApiType.FLOW ->
                "NjaAsync.flow($module, ${member.id}, { njaW, njaS -> $writes }) { njaR -> ${codec.decode(returnType.elementType, "njaR")} }"
            fn.isSuspend ->
                "NjaAsync.call($module, ${member.id}, { njaW, njaS -> $writes }) { njaR -> ${codec.decode(returnType, "njaR")} }"
            else ->
                "NjaRuntime.call($module, ${member.id}, { njaW, njaS -> $writes }) { njaR, njaS -> ${codec.decode(returnType, "njaR")} }"
        }
        val leased = receiver != null && returnType !is ApiType.FLOW
        appendLine("$head =")
        appendLine(if (leased) "$indent    $receiver.use { njaH -> $body }" else "$indent    $body")
    }

    private fun StringBuilder.appendProperty(p: ApiProperty, ownerKey: String, indent: String, receiver: String?, modifiers: String) {
        val getter = membersByOwner.getValue(ownerKey to "get:${p.name}")
        val type = model.clientType(p.type)
        val handle = if (receiver != null) "njaW.writeLong(njaH)" else "Unit"
        val get = "NjaRuntime.call($module, ${getter.id}, { njaW, njaS -> $handle }) { njaR, njaS -> ${codec.decode(p.type, "njaR")} }"
        appendLine("$indent$modifiers${if (p.mutable) "var" else "val"} ${esc(p.name)}: $type")
        appendLine("$indent    get() = ${if (receiver != null) "$receiver.use { njaH -> $get }" else get}")
        if (p.mutable) {
            val setter = membersByOwner.getValue(ownerKey to "set:${p.name}")
            val writes = listOfNotNull(handle.takeIf { receiver != null }, codec.encode(p.type, "value", "njaW")).joinToString("; ")
            val set = "NjaRuntime.call($module, ${setter.id}, { njaW, njaS -> $writes }) { _, _ -> }"
            appendLine("$indent    set(value) { ${if (receiver != null) "$receiver.use { njaH -> $set }" else set} }")
        }
    }

    // ── Module ──────────────────────────────────────────────────────────────────────────────────────────────────

    private fun StringBuilder.appendModule() {
        appendLine("/** The $libName façade's module in the JVM. */")
        appendLine("internal object $moduleObject {")
        appendLine("    val index: Int by lazy { NjaRuntime.module(\"$libName\") }")
        appendLine("}")
        appendLine()

        // Extension and top-level functions
        model.module.functions.forEach { fn ->
            appendFunction(fn, membersByOwner.getValue("top" to signature(fn)), "", receiver = null, modifiers = "")
            appendLine()
        }

        // Objects the JVM sends: wrapped in the proxy of their exact type
        appendLine("internal fun nja_wrap(handle: Long, type: Int): JvmProxy {")
        appendLine("    val ref = JvmRef(handle)")
        appendLine("    return when (type) {")
        model.typeIds.forEach { (fq, id) ->
            val name = model.clientName(fq)
            val cls = model.classesByFq[fq]
            val proxy = when {
                cls == null -> "Nja_${name}_Proxy"
                cls.isAbstract || cls.isSealed -> "Nja_${name}_Proxy"
                else -> name
            }
            appendLine("        $id -> $proxy(ref)")
        }
        appendLine("        else -> throw IllegalStateException(\"NJA: the JVM sent an object of an unknown type (\$type)\")")
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("internal fun nja_readObject(r: WireReader): JvmProxy {")
        appendLine("    val handle = r.readLong()")
        appendLine("    return nja_wrap(handle, r.readInt())")
        appendLine("}")
        appendLine()
        appendLine("internal fun nja_readObjectOrNull(r: WireReader): JvmProxy? {")
        appendLine("    val handle = r.readLong()")
        appendLine("    return if (handle == 0L) null else nja_wrap(handle, r.readInt())")
        appendLine("}")

        // Value types
        for (dc in model.module.dataClasses) {
            appendLine()
            appendLine("internal fun nja_write_${dc.simpleName}(w: WireWriter, value: ${dc.simpleName}, njaS: CallScope) {")
            dc.fields.forEach { f -> appendLine("    ${codec.encode(f.type, "value.${esc(f.name)}", "w")}") }
            appendLine("}")
            appendLine()
            appendLine("internal fun nja_read_${dc.simpleName}(r: WireReader): ${dc.simpleName} = ${dc.simpleName}(")
            dc.fields.forEach { f -> appendLine("    ${esc(f.name)} = ${codec.decode(f.type, "r")},") }
            appendLine(")")
        }
        for (v in model.module.sealedValues) appendSealedCodec(v, v.simpleName, "njaS: CallScope") { "${v.simpleName}.${it.name}" }

        // The JVM's lambdas, by signature
        for ((key, invoke) in model.invokers) {
            val t = invoke.type
            val params = t.paramTypes.mapIndexed { i, p -> "p$i: ${model.clientType(p)}" }.joinToString(", ")
            val writes = (listOf("njaW.writeLong(njaH)") + t.paramTypes.mapIndexed { i, p -> codec.encode(p, "p$i", "njaW") }).joinToString("; ")
            appendLine()
            appendLine("internal class NjaFn_$key(njaRef: JvmRef) : JvmObject(njaRef), ${model.clientType(t)} {")
            appendLine("    override fun invoke($params): ${model.clientType(t.returnType)} =")
            appendLine("        njaRef.use { njaH -> NjaRuntime.call($module, ${invoke.id}, { njaW, njaS -> $writes }) { njaR, njaS -> ${codec.decode(t.returnType, "njaR")} } }")
            appendLine("}")
        }
    }

    // Its case's index, then the case's fields
    private fun StringBuilder.appendSealedCodec(v: ApiSealedValue, type: String, extra: String, caseName: (ApiSealedCase) -> String) {
        appendLine()
        appendLine("internal fun nja_write_${v.simpleName}(w: WireWriter, value: $type, $extra) {")
        appendLine("    when (value) {")
        v.cases.forEachIndexed { i, case ->
            appendLine("        is ${caseName(case)} -> {")
            appendLine("            w.writeInt($i)")
            case.fields.forEach { f -> appendLine("            ${codec.encode(f.type, "value.${esc(f.name)}", "w")}") }
            appendLine("        }")
        }
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("internal fun nja_read_${v.simpleName}(r: WireReader): $type = when (val njaCase = r.readInt()) {")
        v.cases.forEachIndexed { i, case ->
            if (case.isObject) {
                appendLine("    $i -> ${caseName(case)}")
            } else {
                appendLine("    $i -> ${caseName(case)}(")
                case.fields.forEach { f -> appendLine("        ${esc(f.name)} = ${codec.decode(f.type, "r")},") }
                appendLine("    )")
            }
        }
        appendLine("    else -> throw IllegalStateException(\"NJA: unknown case \$njaCase of $type\")")
        appendLine("}")
    }
}
